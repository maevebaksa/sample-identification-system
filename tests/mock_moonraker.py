"""A tiny fake Moonraker for tests and offline demos:  python tests/mock_moonraker.py"""
import time
from pathlib import Path

from flask import Flask, jsonify, request, send_file, abort


def make_mock(gcode_dir: Path):
    app = Flask(__name__)
    gcode_dir.mkdir(parents=True, exist_ok=True)
    app.jobs = []
    app.started = []
    app.state = "standby"

    @app.get("/server/info")
    def info():
        return jsonify(result={"klippy_state": "ready", "moonraker_version": "v0.9.3-mock"})

    @app.get("/server/history/list")
    def hist():
        return jsonify(result={"count": len(app.jobs), "jobs": list(reversed(app.jobs))})

    @app.get("/server/files/gcodes/<path:p>")
    def dl(p):
        f = gcode_dir / p
        return send_file(f) if f.is_file() else abort(404)

    @app.get("/server/files/metadata")
    def meta():
        f = gcode_dir / request.args["filename"]
        if not f.is_file():
            return jsonify(error={"code": 404, "message": "File not found"}), 404
        return jsonify(result={"size": f.stat().st_size, "slicer": "PrusaSlicer"})

    @app.post("/server/files/upload")
    def upload():
        up = request.files["file"]
        folder = request.form.get("path", "")
        dest = gcode_dir / folder / up.filename
        dest.parent.mkdir(parents=True, exist_ok=True)
        up.save(dest)
        if request.form.get("print") == "true":
            app.started.append(f"{folder}/{up.filename}".lstrip("/"))
        return jsonify(result={"item": {"path": up.filename}})

    @app.get("/printer/objects/query")
    def query():
        return jsonify(result={"status": {"print_stats": {"state": app.state}}})

    @app.post("/printer/print/start")
    def start():
        app.started.append(request.args["filename"])
        return jsonify(result="ok")

    def add_job(job_id, filename, content, status="completed", start=None):
        f = gcode_dir / filename
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content)
        app.jobs.append({"job_id": job_id, "filename": filename, "status": status,
                         "start_time": start or time.time(), "end_time": time.time(),
                         "print_duration": 3600.0, "total_duration": 3700.0, "filament_used": 4200.0,
                         "metadata": {"slicer": "PrusaSlicer", "layer_height": 0.2, "size": f.stat().st_size,
                                      "thumbnails": [{"width": 1}]}})
    app.add_job = add_job
    return app


if __name__ == "__main__":
    import tempfile
    d = Path(tempfile.mkdtemp())
    m = make_mock(d / "gcodes")
    m.add_job("000001", "demo.gcode", "; generated by PrusaSlicer 2.7.0 on x\n; layer_height = 0.2\n; temperature = 215\n")
    m.run(port=7125)
