from mock_moonraker import make_mock  # noqa: E402
from sis.app import create_app  # noqa: E402
from sis.gcode_meta import parse_gcode_settings  # noqa: E402

GCODE_A = ("; generated by PrusaSlicer 2.7.0 on 2026-01-01\nG28\nG1 X1\n"
           "; layer_height = 0.2\n; temperature = 215\n; fill_density = 15%\n; filament_type = PLA\n")
GCODE_B = GCODE_A.replace("temperature = 215", "temperature = 225").replace("15%", "25%")


@pytest.fixture()
def env(tmp_path):
    mock = make_mock(tmp_path / "mr_gcodes")
    srv = make_server("127.0.0.1", 0, mock, threaded=True)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    cfg = {"moonraker_url": f"http://127.0.0.1:{srv.port}", "moonraker_api_key": "", "public_url": "",
           "data_dir": tmp_path / "data", "poll_seconds": 30, "initial_import_count": 10}
    app = create_app(cfg)
    yield mock, app, app.test_client(), tmp_path
    srv.shutdown()


def test_parse_settings(tmp_path):
    p = tmp_path / "a.gcode"
    p.write_text(GCODE_A)
    s = parse_gcode_settings(p)
    assert s["slicer"] == "PrusaSlicer" and s["layer_height"] == "0.2" and s["fill_density"] == "15%"


def test_full_flow(env):
    mock, app, c, tmp = env
    t = time.time()
    mock.add_job("1", "a.gcode", GCODE_A, start=t - 200)
    mock.add_job("2", "sub/b.gcode", GCODE_B, start=t - 100)
    mock.add_job("3", "running.gcode", GCODE_A, status="in_progress", start=t - 5)

    assert c.post("/api/sync").json["new"] == 2
    assert c.post("/api/sync").json["new"] == 0          # idempotent
    rows = c.get("/api/samples").json
    assert sorted(r["id"] for r in rows) == [1, 2]       # in-progress job not imported

    # archive is a real copy that survives deletion from Moonraker
    s1 = c.get("/api/samples/1").json
    assert (tmp / "data" / "gcodes" / s1["gcode_path"]).read_text() == GCODE_A
    assert s1["settings"]["temperature"] == "215" and s1["settings"]["meta.slicer"] == "PrusaSlicer"

    # mark results
    assert c.patch("/api/samples/1", json={"result": "success", "notes": "nice"}).json["result"] == "success"
    c.patch("/api/samples/2", json={"result": "fail"})
    assert c.patch("/api/samples/2", json={"result": "bogus"}).status_code == 400

    # compare shows differing keys first
    cmp_ = c.get("/api/compare?ids=1,2").json
    diff = {r["key"] for r in cmp_["rows"] if r["differs"]}
    assert {"temperature", "fill_density"} <= diff and "layer_height" not in diff

    # export
    csv_text = c.get("/api/export.csv?settings=key").data.decode()
    assert "temperature" in csv_text and "success" in csv_text and csv_text.count("\n") >= 3
    assert c.get("/api/export.json?ids=1").json[0]["id"] == 1

    # reprint existing file -> just starts it
    r = c.post("/api/samples/1/reprint").json
    assert r == {"started": "a.gcode", "uploaded": False}

    # delete from Moonraker, then reprint -> restored from archive
    (tmp / "mr_gcodes" / "sub" / "b.gcode").unlink()
    r = c.post("/api/samples/2/reprint").json
    assert r["uploaded"] and mock.started[-1] == "sub/b.gcode"
    assert (tmp / "mr_gcodes" / "sub" / "b.gcode").read_text() == GCODE_B

    # busy printer is refused
    mock.state = "printing"
    assert c.post("/api/samples/1/reprint").status_code == 502


def test_reprint_detected_and_photo(env):
    mock, app, c, tmp = env
    t = time.time()
    mock.add_job("1", "a.gcode", GCODE_A, start=t - 200)
    c.post("/api/sync")
    mock.add_job("2", "a.gcode", GCODE_A, start=t - 100)   # same file printed again
    c.post("/api/sync")
    assert c.get("/api/samples/2").json["reprint_of"] == 1

    r = c.post("/api/samples/1/photos", data={"photo": (io.BytesIO(b"\xff\xd8fake"), "x.jpg")},
               content_type="multipart/form-data")
    assert r.status_code == 200
    photo = c.get("/api/samples/1").json["photos"][0]
    assert c.get("/photos/" + photo["filename"]).status_code == 200
    assert c.get("/api/samples/1/qr.svg").data.startswith(b"<svg")
    assert c.delete(f"/api/photos/{photo['id']}").status_code == 200


def test_file_already_deleted_before_sync(env):
    mock, app, c, tmp = env
    mock.add_job("1", "gone.gcode", GCODE_A)
    (tmp / "mr_gcodes" / "gone.gcode").unlink()
    assert c.post("/api/sync").json["new"] == 1
    s = c.get("/api/samples/1").json
    assert s["gcode_path"] is None and s["archive_error"]
    assert c.post("/api/samples/1/reprint").status_code == 502


def test_archive(env):
    mock, app, c, tmp = env
    t = time.time()
    mock.add_job("1", "a.gcode", GCODE_A, start=t - 200)
    mock.add_job("2", "b.gcode", GCODE_B, start=t - 100)
    c.post("/api/sync")
    c.patch("/api/samples/1", json={"result": "success"})
    c.post("/api/samples/archive", json={"unrated": True})
    rows = {r["id"]: r for r in c.get("/api/samples").json}
    assert rows[1]["archived"] == 0 and rows[2]["archived"] == 1
    assert "b.gcode" not in c.get("/api/export.csv").data.decode()      # excluded by default
    c.post("/api/samples/archive", json={"ids": [2], "archived": False})
    assert c.get("/api/samples/2").json["archived"] == 0
    assert c.patch("/api/samples/1", json={"archived": True}).json["archived"] == 1
    c.post("/api/sync")                                                  # archived stays archived, not re-imported
    assert len(c.get("/api/samples").json) == 2
