def write(tmp_path, text, name="x.gcode"):
    p = tmp_path / name
    p.write_text(text)
    return p


def test_detect_from_prusa_orca_cura_klipper(tmp_path):
    prusa = write(tmp_path, "G28\n; printing object Benchy.stl id:0 copy 0\nG1 X1\n")
    assert detect_model(prusa, "a.gcode") == ("Benchy.stl", "benchy")
    cura = write(tmp_path, ";MESH:NONMESH\n;MESH:benchy.STL\nG1 X1\n")
    assert detect_model(cura, "a.gcode")[1] == "benchy"                     # same key as the Prusa one
    klipper = write(tmp_path, "EXCLUDE_OBJECT_DEFINE NAME=Benchy_stl_id_0_copy_0 CENTER=1,1\n")
    assert detect_model(klipper, "a.gcode")[1] == "benchy"
    multi = write(tmp_path, "; printing object b.stl id:1 copy 0\n; printing object a.stl id:0 copy 0\n")
    assert detect_model(multi, "a.gcode") == ("b.stl, a.stl", "a+b")


def test_filename_fallback():
    assert model_from_filename("sub/Cube_0.2mm_PLA_MK3S_1h5m.gcode") == "Cube MK3S"
    assert normalize_model("Cube.STL") == normalize_model("cube") == "cube"
    p = Path("does-not-exist.gcode")
    assert detect_model(p, "Gear_0.16mm_PETG_30m.gcode")[1] == "gear"


def test_same_model_grouping(env):
    mock, app, c, tmp = env
    t = time.time()
    body = "; generated by PrusaSlicer 2.7.0\n; printing object Cube.stl id:0 copy 0\n; temperature = %s\n"
    mock.add_job("1", "cube_a.gcode", body % 210, start=t - 300)
    mock.add_job("2", "totally_different_name.gcode", body % 230, start=t - 200)   # same STL, other settings
    mock.add_job("3", "gear.gcode", "; printing object Gear.stl id:0 copy 0\n", start=t - 100)
    c.post("/api/sync")

    s1 = c.get("/api/samples/1").json
    assert s1["model"] == "Cube.stl" and s1["model_key"] == "cube"
    assert [r["id"] for r in c.get("/api/samples/1/related").json] == [2]
    assert c.get("/api/samples/3/related").json == []

    # manual override re-groups
    c.patch("/api/samples/3", json={"model": "cube"})
    assert [r["id"] for r in c.get("/api/samples/1/related").json] == [2, 3]
    assert "Cube.stl" in c.get("/api/export.csv").data.decode()
