"""Extract slicer settings from a gcode file.

Supported (best effort, from the head and tail of the file only - never the whole
file, which can be hundreds of MB):

* PrusaSlicer / SuperSlicer / OrcaSlicer / Bambu Studio: full config as ``; key = value`` lines.
* Cura: header comments (``;FLAVOR:``, ``;TIME:`` ...) and the ``;SETTING_3`` block. Note that Cura
  only writes the settings you *changed* from the base profile into the file, so unchanged settings
  can't be recovered from the gcode. Temperatures are additionally read from the start G-code.
* Any slicer: first nozzle / bed temperature commanded by the start G-code.
"""
import json
import re

HEAD_BYTES = 256 * 1024
TAIL_BYTES = 3 * 1024 * 1024
MAX_VALUE_LEN = 4000

_KV = re.compile(r"^; ?([A-Za-z0-9_\[\]\.\-]+) = (.*)$")
_GENERATED = re.compile(r"^; ?generated by ([A-Za-z0-9_ \-]+?) (\d[\w\.\-\+]*)", re.I)
_CURA_GEN = re.compile(r"^;Generated with ([A-Za-z0-9_]+) ?([\w\.\-]*)", re.I)
_CURA_HEADER = re.compile(r"^;(FLAVOR|TIME|LAYER_COUNT|TARGET_MACHINE\.NAME|MINX|MINY|MINZ|MAXX|MAXY|MAXZ|"
                          r"Filament used|Layer height):\s*(.+)$")
_TEMP = re.compile(r"^(M104|M109|M140|M190)\b[^;]*?\bS(\d+(?:\.\d+)?)", re.I)


def _read_chunks(path):
    with open(path, "rb") as f:
        f.seek(0, 2)
        size = f.tell()
        f.seek(0)
        head = f.read(HEAD_BYTES)
        tail = b""
        if size > HEAD_BYTES:
            f.seek(max(HEAD_BYTES, size - TAIL_BYTES))
            tail = f.read()
    return head.decode("utf-8", "ignore"), tail.decode("utf-8", "ignore")


def parse_gcode_settings(path):
    head, tail = _read_chunks(path)
    out = {}

    for line in head.splitlines():
        m = _GENERATED.match(line)
        if m:
            out["slicer"], out["slicer_version"] = m.group(1).strip(), m.group(2)
            break
        m = _CURA_GEN.match(line)
        if m:
            out["slicer"], out["slicer_version"] = "Cura", m.group(2) or m.group(1)
            break

    # Key/value config blocks (head first so the tail wins on duplicates).
    for text in (head, tail):
        for line in text.splitlines():
            m = _KV.match(line.rstrip())
            if m:
                out[m.group(1)] = m.group(2).strip()[:MAX_VALUE_LEN]

    out.update(_derive_from_gcode(head))
    out.update(_parse_cura(head, tail))
    return out


def _parse_cura(head, tail):
    out = {}
    for line in head.splitlines():
        m = _CURA_HEADER.match(line.strip())
        if m:
            out["cura." + m.group(1).lower().replace(" ", "_")] = m.group(2).strip()

    # Cura wraps one long JSON line into many ";SETTING_3 <chunk>" lines.
    parts = [ln[len(";SETTING_3 "):].rstrip("\r\n")
             for ln in (tail or head).splitlines() if ln.startswith(";SETTING_3 ")]
    if not parts:
        return out
    blob = "".join(parts)
    sections, multi = [], False
    try:
        data = json.loads(blob)
        sections.append(("", data.get("global_quality", "")))
        ext = data.get("extruder_quality", [])
        multi = len(ext) > 1
        sections += [(f"extruder{i}.", e) for i, e in enumerate(ext)]
    except ValueError:                      # damaged JSON: scrape what we can
        sections.append(("", blob))

    for prefix, text in sections:
        if not isinstance(text, str):
            continue
        # Cura double-escapes newlines inside the JSON strings.
        text = text.replace("\\\\n", "\n").replace("\\n", "\n")
        area = None
        for line in text.splitlines():
            line = line.strip()
            if line.startswith("["):
                area = line
                continue
            if " = " not in line:
                continue
            k, v = (x.strip() for x in line.split(" = ", 1))
            if area == "[general]" and not prefix and k == "name":
                out["cura.profile_name"] = v[:200]
            elif area == "[general]" and not prefix and k == "definition":
                out["cura.machine_definition"] = v[:200]
            elif area == "[values]" and k and len(k) < 80:
                out[(prefix if multi else "") + k] = v[:MAX_VALUE_LEN]
    return out


def _derive_from_gcode(head):
    """Temperatures actually commanded by the start G-code (works for any slicer)."""
    out = {}
    for line in head.splitlines()[:3000]:
        m = _TEMP.match(line.strip())
        if not m:
            continue
        cmd, val = m.group(1).upper(), m.group(2)
        key = "gcode.first_nozzle_temp" if cmd in ("M104", "M109") else "gcode.first_bed_temp"
        if float(val) > 0:
            out.setdefault(key, val)
    return out


# ----------------------------------------------------------------- model name
# Slicers that "label objects" write the source model's name into the gcode:
#   PrusaSlicer/Orca/Bambu: "; printing object cube.stl id:0 copy 0"
#   Cura:                   ";MESH:cube.stl"
#   Klipper exclude_object: "EXCLUDE_OBJECT_DEFINE NAME=cube_stl_id_0_copy_0 ..."
_OBJ_PATTERNS = [
    re.compile(r"^; ?printing object (.+?) id:\d+", re.M),
    re.compile(r"^;MESH:(?!NONMESH)(.+?)\s*$", re.M),
    re.compile(r"^EXCLUDE_OBJECT_DEFINE NAME=(\S+?)(?:_id_\d+_copy_\d+)?(?:\s|$)", re.M),
]
MODEL_SCAN_BYTES = 2 * 1024 * 1024
_EXT = re.compile(r"[._](stl|3mf|obj|step|stp|amf)$|\.(gcode|gco|bgcode)$", re.I)
_FNAME_NOISE = [
    re.compile(r"^\d+(\.\d+)?mm$", re.I),               # 0.2mm
    re.compile(r"^\d+h(\d+m)?$|^\d+m$", re.I),          # 1h5m, 45m
    re.compile(r"^(pla|petg|abs|asa|tpu|pc|pa|pet|pva|hips|pla\+|pa12|pa6|cf|gf|plus)$", re.I),
    re.compile(r"^\d+(\.\d+)?g$", re.I),                # 12g
]


def normalize_model(name):
    """Canonical key so 'Cube.STL', 'cube.stl' and 'cube' group together."""
    n = (name or "").replace("\\", "/").split("/")[-1].strip()
    n = _EXT.sub("", n)
    return re.sub(r"\s+", " ", n).strip().lower()


def extract_model_names(path):
    """Unique source-model names found in the gcode, in order of appearance."""
    with open(path, "rb") as f:
        text = f.read(MODEL_SCAN_BYTES).decode("utf-8", "ignore")
    for pat in _OBJ_PATTERNS:
        names = []
        for m in pat.finditer(text):
            n = m.group(1).strip()
            if n and n not in names:
                names.append(n)
        if names:
            return names
    return []


def model_from_filename(filename):
    """Guess the model name from a slicer-style filename by dropping layer height, filament and time tokens."""
    base = _EXT.sub("", filename.replace("\\", "/").split("/")[-1])
    tokens = [t for t in re.split(r"[_\s]+", base) if t]
    keep = [t for t in tokens if not any(p.match(t) for p in _FNAME_NOISE)]
    return " ".join(keep) if keep else base


def detect_model(path, filename):
    """(display name, grouping key) for a sample."""
    names = []
    try:
        names = extract_model_names(path) if path else []
    except OSError:
        pass
    if not names:
        names = [model_from_filename(filename)]
    keys = sorted({normalize_model(n) for n in names})
    return ", ".join(names), "+".join(keys)


_SKIP_META = {"thumbnails", "filename", "modified", "job_id", "uuid", "gcode_images"}


def flatten_moonraker_metadata(meta):
    """Moonraker's parsed file metadata -> flat {'meta.<key>': str} dict."""
    out = {}
    for k, v in (meta or {}).items():
        if k in _SKIP_META or v is None:
            continue
        if isinstance(v, (list, tuple)):
            v = ", ".join(str(x) for x in v)
        elif isinstance(v, dict):
            continue
        out["meta." + k] = str(v)
    return out
